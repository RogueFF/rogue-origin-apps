#!/usr/bin/env node
/**
 * Builds workers/migrations-demo/demo-schema.sql: everything the practice / demo
 * database (DEMO_DB, rogue-origin-demo; lib/demo-env.js) needs, from the same
 * sources as the live database, so the two never drift:
 *   - scale_readings as it was before 0049 (schema.sql already carries later columns),
 *     and the two other base tables the floor reads, from schema.sql;
 *   - the cell + order migrations, in order;
 *   - the demo driver's own tables (demo_state, demo_arrivals, demo_jobs).
 * Run it after adding a cell/order migration; tests/demo-schema.test.mjs (root, run in CI) fails
 * when the committed file is stale.
 *
 *   node workers/scripts/build-demo-schema.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const W = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BASE_TABLES = ['monthly_production', 'system_config'];
const SCALE_READINGS_BASE = 'CREATE TABLE IF NOT EXISTS scale_readings (station_id TEXT PRIMARY KEY, weight REAL, target_weight REAL, unit TEXT, updated_at TEXT);';
export const MIGRATIONS = [
  '0049-cell-table-stations', '0050-cell-hourly', '0052-cell-job-order', '0053-scale-down-since',
  '0054-cell-screen-state', '0055-scale-node-battery', '0056-scale-untracked-since',
  '0058-order-queue', '0060-pickup-spot', '0061-order-assign',
];
const DEMO_TABLES = `-- The demo driver's own state (handlers/production/demo.js).
CREATE TABLE IF NOT EXISTS demo_state (key TEXT PRIMARY KEY, value TEXT NOT NULL);
-- The marker the Worker checks before any demo request (lib/demo-env.js verifyDemoDb):
-- a binding pointed at the live database by mistake has no such row, and is refused.
INSERT OR IGNORE INTO demo_state (key, value) VALUES ('database', 'rogue-origin-demo');
CREATE TABLE IF NOT EXISTS demo_arrivals (
  id      INTEGER PRIMARY KEY AUTOINCREMENT,
  sim_at  INTEGER NOT NULL,      -- sim clock ms when the order arrives
  payload TEXT NOT NULL,         -- the mock order: name, rush, lines (no buyer fields)
  done    INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_demo_arrivals_due ON demo_arrivals (done, sim_at);
-- When (sim clock ms) the demo first saw each order assigned / ready / collected:
-- auto bag/tag times its steps on the sim clock, never on the database's wall clock.
CREATE TABLE IF NOT EXISTS demo_orders (
  order_id     INTEGER PRIMARY KEY,
  seen_at      INTEGER,
  ready_at     INTEGER,
  collected_at INTEGER
);
CREATE TABLE IF NOT EXISTS demo_jobs (
  job_id       INTEGER PRIMARY KEY,  -- cell_jobs.id being trimmed
  grams        REAL NOT NULL DEFAULT 0,
  phase        TEXT NOT NULL DEFAULT 'trim',   -- trim | swapped
  swapped_real INTEGER
);
`;

export function buildDemoSchema() {
  const schema = readFileSync(join(W, 'schema.sql'), 'utf8');
  const parts = ['-- GENERATED by workers/scripts/build-demo-schema.mjs: do not edit by hand.',
    '-- The practice / demo database (DEMO_DB = rogue-origin-demo) only. NEVER run this on the live database.',
    '-- Apply once to a fresh rogue-origin-demo:',
    '--   cd workers && npx wrangler d1 execute rogue-origin-demo --remote --file=migrations-demo/demo-schema.sql',
    ''];
  parts.push('-- scale_readings before 0049 adds its columns', SCALE_READINGS_BASE, '');
  for (const t of BASE_TABLES) {
    const m = new RegExp(`CREATE TABLE IF NOT EXISTS ${t} \\([\\s\\S]*?\\n\\);`).exec(schema);
    if (!m) throw new Error(`schema.sql has no ${t}`);
    parts.push(`-- from schema.sql: ${t}`, m[0], '');
  }
  for (const m of MIGRATIONS) {
    parts.push(`-- ===== migrations/${m}.sql =====`, readFileSync(join(W, 'migrations', `${m}.sql`), 'utf8').trim(), '');
  }
  parts.push(DEMO_TABLES);
  return parts.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(join(W, 'migrations-demo'), { recursive: true });
  writeFileSync(join(W, 'migrations-demo', 'demo-schema.sql'), buildDemoSchema());
  console.log('wrote workers/migrations-demo/demo-schema.sql');
}
